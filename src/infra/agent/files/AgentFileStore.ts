/**
 * Файлы персонального корня пользователя агента конфигуратора.
 *
 * Все пути — относительные POSIX-пути от персонального корня (`workspace/<projectId>/cf/...`):
 * ровно в таком виде их понимает и сам агент (`--dir`, `--list-file`), и SFTP-сервер агента,
 * чей корень уже персональный. Алгоритмы синхронизации работают только через этот контракт и
 * не знают, лежит корень на локальном диске (агент на этой машине) или на удалённом сервере.
 */
export interface AgentFileEntry {
  /** Путь от персонального корня, POSIX; у корня — пустая строка. */
  readonly path: string;
  readonly type: 'file' | 'dir';
  /** Размер в байтах; у каталога — 0. */
  readonly size: number;
}

/**
 * Общие правила для всех методов:
 *  - путь — относительный POSIX; абсолютный путь или сегмент `..` — отказ до обращения к ФС;
 *  - ссылки (symlink/junction): путь, реальное расположение которого после разрешения ссылок
 *    оказывается вне персонального корня, — отказ «за пределы корня агента» (у `stat` — для
 *    существующего пути; отсутствующий даёт `undefined`). Ссылка, ведущая внутрь корня,
 *    прозрачна. Реализация без ссылок (SFTP агента) это правило выполняет тривиально.
 */
export interface AgentFileStore {
  readonly kind: 'local' | 'sftp';
  /**
   * `undefined`, если пути нет (в том числе когда промежуточный элемент — файл); иные отказы
   * (права, недопустимое имя) пробрасываются. По ссылке следует: описывает её цель.
   */
  stat(rel: string): Promise<AgentFileEntry | undefined>;
  readFile(rel: string): Promise<Buffer>;
  /** Создаёт промежуточные каталоги; подменяет цель целиком (temp+rename на стороне хранилища). */
  writeFile(rel: string, data: Uint8Array | string): Promise<void>;
  /**
   * Удаляет файл или каталог; отсутствующий путь — не ошибка. Непустой каталог без
   * `recursive` — отказ (SFTP агента удаляет непустой каталог по `rmdir` рекурсивно,
   * поэтому проверка обязательна в каждой реализации). Корень удалить нельзя. Ссылка
   * удаляется сама по себе, её цель не затрагивается.
   */
  remove(rel: string, options?: { readonly recursive?: boolean }): Promise<void>;
  /**
   * Содержимое каталога, отсортированное по пути; пути — от корня хранилища. Несуществующий
   * каталог или файл вместо каталога — отказ (не пустой список: «M ещё нет» и «M пусто» —
   * разные состояния). Ссылки не перечисляются и не обходятся.
   */
  list(relDir: string, options?: { readonly recursive?: boolean }): Promise<AgentFileEntry[]>;
  mkdirp(rel: string): Promise<void>;
  dispose(): Promise<void>;
}

/**
 * Сегменты относительного пути агента. Общая проверка для всех реализаций хранилища:
 * абсолютный путь (POSIX или с диском Windows) и сегмент `..` отвергаются ДО обращения к
 * ФС/серверу — иначе путь из list-файла или ответа агента мог бы адресовать файл вне
 * персонального корня. Обратные слэши приводятся к `/`, пустые сегменты и `.` схлопываются;
 * пустой результат — сам корень.
 */
export function toAgentPathSegments(rel: string): string[] {
  const normalized = rel.replace(/\\/g, '/');
  if (normalized.startsWith('/') || /^[A-Za-z]:/.test(normalized)) {
    throw new Error(`Путь агента должен быть относительным: ${rel}`);
  }
  const segments = normalized.split('/').filter((segment) => segment !== '' && segment !== '.');
  if (segments.includes('..')) {
    throw new Error(`Путь агента выходит за пределы корня агента: ${rel}`);
  }
  return segments;
}
